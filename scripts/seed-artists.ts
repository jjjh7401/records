const MIN_SCORE = 80;

interface SeedSummary {
  name: string;
  picked: string;
  score: number;
  mbid: string;
  album: string;
  tracks: number;
  statements: number;
}

async function pickArtist(name: string): Promise<{ mbid: string; name: string; score: number } | null> {
  const q = SEARCH_OVERRIDE[name] ?? name;
  // 오버라이드 검색(예: バルーン)은 country 필터 없이 — MB에 country가 비어 있는 경우가 있음
  const query = SEARCH_OVERRIDE[name]
    ? `artist:"${q.replace(/"/g, "")}"`
    : `artist:"${q.replace(/"/g, "")}" AND country:JP`;
  const res: any = await mb(`/artist?query=${encodeURIComponent(query)}&fmt=json&limit=5`);
  const candidates: any[] = (res.artists ?? []).filter((a: any) => (a.score ?? 0) >= MIN_SCORE);
  if (!candidates.length) return null;
  // JP이면서 점수 최고
  candidates.sort((a, b) => b.score - a.score);
  const top = candidates[0];
  return { mbid: top.id, name: top.name, score: top.score };
}

async function pickDebutAlbum(artistMbid: string): Promise<{ mbid: string; title: string } | null> {
  const res: any = await mb(
    `/release-group?artist=${artistMbid}&fmt=json&limit=100`,
  );
  const rgs: any[] = res["release-groups"] ?? [];
  // Album 우선, 없으면 EP로 폴백 (YOASOBI처럼 EP만 있는 아티스트 대응)
  let pool = rgs.filter(
    (rg: any) => rg["primary-type"] === "Album" && rg["first-release-date"],
  );
  if (!pool.length) {
    pool = rgs.filter((rg: any) => rg["primary-type"] === "EP" && rg["first-release-date"]);
  }
  if (!pool.length) return null;
  pool.sort((a, b) => String(a["first-release-date"]).localeCompare(String(b["first-release-date"])));
  const top = pool[0];
  return { mbid: top.id, title: top.title };
}

// 검색명 오버라이드 (별명/예명이 본명보다 잘 걸리는 경우)
const SEARCH_OVERRIDE: Record<string, string> = {
  "須田景凪": "バルーン",
};

async function main() {
  const args = process.argv.slice(2);
  const out = args[args.indexOf("--out") + 1] ?? "/tmp/seed_jpop.sql";
  const onlyIdx = args.indexOf("--only");
  const onlyNames =
    onlyIdx >= 0 ? args[onlyIdx + 1].split(",").map((s) => s.trim()) : null;
  const targets = onlyNames ?? ARTISTS;

  const all: string[] = [
    "-- Phase C seed batch: J-POP artists (idempotent)",
    "-- Generated by scripts/seed-artists.ts. Source: MusicBrainz (canonical).",
    "-- Review before applying.",
    "",
  ];
  const summary: SeedSummary[] = [];
  const skipped: string[] = [];

  for (const name of targets) {
    try {
      const artist = await pickArtist(name);
      if (!artist) {
        console.log(`SKIP ${name}: no confident match`);
        skipped.push(name);
        continue;
      }
      const album = await pickDebutAlbum(artist.mbid);
      if (!album) {
        console.log(`SKIP ${name}: no album found`);
        skipped.push(name);
        continue;
      }
      const { title, trackCount, statements } = await ingestReleaseGroup(album.mbid);
      all.push(`-- ===== ${name} → ${title} (${trackCount} tracks) =====`);
      all.push(...statements, "");
      summary.push({
        name,
        picked: artist.name,
        score: artist.score,
        mbid: artist.mbid,
        album: title,
        tracks: trackCount,
        statements: statements.length,
      });
      console.log(`OK ${name} → ${title} (${trackCount} tracks)`);
    } catch (e) {
      console.log(`FAIL ${name}: ${(e as Error).message}`);
      skipped.push(name);
    }
  }

  writeFileSync(out, all.join("\n") + "\n");
  console.log(`\n===== SUMMARY =====`);
  console.log(`artists ok: ${summary.length}, skipped: ${skipped.length}`);
  if (skipped.length) console.log(`skipped: ${skipped.join(", ")}`);
  const totalTracks = summary.reduce((s, x) => s + x.tracks, 0);
  console.log(`total tracks: ${totalTracks}, total statements: ${all.length}`);
  console.log(`written: ${out}`);
  // 정합성 체크용 요약 출력
  for (const s of summary) {
    console.log(`- ${s.name} (${s.picked}, score ${s.score}) → ${s.album}: ${s.tracks} tracks`);
  }
}

main().catch((e) => {
  console.error("FAILED:", e.message);
  process.exit(1);
});
